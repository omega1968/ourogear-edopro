Duel.LoadScript('constant.lua')
Duel.LoadScript('utility.lua')
Debug.ReloadFieldBegin(0)
Debug.SetPlayerInfo(0,8000,0,0)
Debug.SetPlayerInfo(1,8000,0,0)
local target=Debug.AddCard(990071001,0,0,LOCATION_MZONE,0,POS_FACEUP_ATTACK)
local harness=Debug.AddCard(990071015,0,0,LOCATION_DECK,0,POS_FACEDOWN)
local recruit=Debug.AddCard(990071002,0,0,LOCATION_DECK,0,POS_FACEDOWN)
local driver=Debug.AddCard(990071018,0,0,LOCATION_SZONE,1,POS_FACEUP)
Debug.ReloadFieldEnd()
local stage=0
local run=Effect.CreateEffect(driver)
run:SetType(EFFECT_TYPE_IGNITION)
run:SetRange(LOCATION_SZONE)
run:SetDescription(0x7fffff)
run:SetCondition(function() return stage==0 end)
run:SetOperation(function(e,tp)
    stage=1
    Duel.Equip(tp,harness,target)
end)
driver:RegisterEffect(run)
local verify=run:Clone()
verify:SetCondition(function() return stage==1 end)
verify:SetOperation(function()
    assert(harness:IsLocation(LOCATION_SZONE) and harness:GetEquipTarget()==target,'Drastea-style equip failed')
    assert(recruit:IsLocation(LOCATION_MZONE),'Harness did not Special Summon a Level 4 after effect-based equip')
    Debug.Message('PASS actions: effect-based equip triggers Harness Level 4 Special Summon')
    Duel.Win(0,0x99)
end)
driver:RegisterEffect(verify)
