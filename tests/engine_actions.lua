Duel.LoadScript('constant.lua')
Duel.LoadScript('utility.lua')
Debug.ReloadFieldBegin(0)
Debug.SetPlayerInfo(0,8000,0,0)
Debug.SetPlayerInfo(1,8000,0,0)
local frame=Debug.AddCard(990071010,0,0,LOCATION_MZONE,0,POS_FACEUP_ATTACK,true)
local old1=Debug.AddCard(990071012,0,0,LOCATION_MZONE,0,POS_FACEUP_ATTACK)
local old2=Debug.AddCard(990071001,0,0,LOCATION_MZONE,0,POS_FACEUP_ATTACK)
local token=Debug.AddCard(990071099,0,0,LOCATION_MZONE,1,POS_FACEUP_DEFENSE)
local relay=Debug.AddCard(OG_TEST_VARIANT and 990071012 or 990071011,0,0,LOCATION_EXTRA,0,POS_FACEDOWN)
local top=Debug.AddCard(990071002,0,0,LOCATION_DECK,0,POS_FACEDOWN)
Debug.ReloadFieldEnd()
local run=Effect.CreateEffect(frame)
run:SetType(EFFECT_TYPE_FIELD|EFFECT_TYPE_CONTINUOUS)
run:SetCode(EVENT_STARTUP)
run:SetOperation(function(e,tp)
    local proc=relay:GetCardEffect(EFFECT_SPSUMMON_PROC)
    assert(proc,'missing Xyz procedure')
    local mats=Group.FromCards(frame,token)
    assert(Ourogear.ValidXyzGroup(mats,relay,0,4,4,2),'valid substitute group rejected')
    Duel.XyzSummon(0,relay,nil,mats,2,2)
    assert(relay:IsSummonType(SUMMON_TYPE_XYZ) and relay:IsLocation(LOCATION_MZONE),'native Xyz procedure failed')
    assert(not token:IsLocation(LOCATION_MZONE),'Token was not consumed')
    assert(relay:GetOverlayCount()==4,'Token top-deck replacement did not attach exactly once')
    assert(relay:GetOverlayGroup():IsContains(top),'wrong Token replacement card')
    assert(relay:GetAttack()==relay:GetBaseAttack()+500,'Vector inherited stat effect failed')
    assert(frame:IsLocation(LOCATION_OVERLAY) and old1:IsLocation(LOCATION_OVERLAY) and old2:IsLocation(LOCATION_OVERLAY),'carry-over cards lost')
    Debug.Message('PASS actions: mixed Xyz/Token substitution, carry-over, deck attachment, inherited stats')
    Duel.Win(0,0x99)
end)
Duel.RegisterEffect(run,0)
