Duel.LoadScript('constant.lua')
Duel.LoadScript('utility.lua')
Debug.ReloadFieldBegin(0)
Debug.SetPlayerInfo(0,8000,0,0)
Debug.SetPlayerInfo(1,8000,0,0)
local siege=Debug.AddCard(990071013,0,0,LOCATION_MZONE,0,POS_FACEUP_ATTACK,true)
for i=1,(OG_TEST_VARIANT and 10 or 9) do Debug.AddCard(990071001,0,0,LOCATION_MZONE,0,POS_FACEUP_ATTACK) end
local loom=Debug.AddCard(990071019,0,0,LOCATION_SZONE,0,POS_FACEUP)
local top=Debug.AddCard(990071002,0,0,LOCATION_DECK,0,POS_FACEDOWN)
Debug.ReloadFieldEnd()
local run=Effect.CreateEffect(siege)
run:SetType(EFFECT_TYPE_IGNITION)
run:SetCode(EVENT_FREE_CHAIN)
run:SetDescription(0x7fffff)
run:SetRange(LOCATION_MZONE)
run:SetOperation(function(e,tp)
    if OG_TEST_VARIANT then
        assert(siege:RemoveOverlayCard(0,1,1,REASON_COST)==1,'ordinary detach failed')
        assert(top:IsLocation(LOCATION_DECK),'declined Loom still attached a card')
        assert(siege:GetFlagEffect(Ourogear.FLAG_LOOM_USED)>0,'declining Loom did not consume first opportunity')
        assert(not siege:CheckRemoveOverlayCard(0,10,REASON_COST),'Loom incorrectly available for second detach')
    else
        assert(siege:CheckRemoveOverlayCard(0,10,REASON_COST),'Loom cannot make 9 materials pay detach 10')
        assert(siege:RemoveOverlayCard(0,10,10,REASON_COST)==10,'full detach cost not paid')
        assert(siege:GetOverlayCount()==0,'Loom incorrectly waived part of the detach cost')
        assert(top:IsLocation(LOCATION_GRAVE),'top card not attached then detached')
        assert(siege:GetFlagEffect(Ourogear.FLAG_LOOM_USED)>0,'first detach not tracked')
    end
    Debug.Message('PASS actions: Material Loom cost augmentation and declining-first-use tracking')
    Duel.Win(0,0x99)
end)
siege:RegisterEffect(run)
