Duel.LoadScript('constant.lua')
Duel.LoadScript('utility.lua')
Debug.ReloadFieldBegin(0)
Debug.SetPlayerInfo(0,8000,0,0)
Debug.SetPlayerInfo(1,8000,0,0)
local xyz=Debug.AddCard(990071014,0,0,LOCATION_MZONE,0,POS_FACEUP_ATTACK)
local ritual=Debug.AddCard(990071007,0,0,LOCATION_HAND,0,POS_FACEDOWN)
local warrior=Debug.AddCard(990071007,0,0,LOCATION_HAND,0,POS_FACEDOWN)
Debug.AddCard(990071004,0,0,LOCATION_HAND,0,POS_FACEDOWN)
Debug.AddCard(990071007,0,0,LOCATION_DECK,0,POS_FACEDOWN)
local naga=Debug.AddCard(990071008,0,0,LOCATION_MZONE,1,POS_FACEUP_ATTACK)
local recovery=Debug.AddCard(990071018,0,0,LOCATION_SZONE,0,POS_FACEUP)
local grid=Debug.AddCard(990071021,0,0,LOCATION_SZONE,1,POS_FACEUP)
if OG_TEST_WITH_CIRCUIT then Debug.AddCard(990071017,0,0,LOCATION_SZONE,2,POS_FACEUP) end
Debug.ReloadFieldEnd()
local wr=Effect.CreateEffect(warrior)
wr:SetType(EFFECT_TYPE_SINGLE)
wr:SetCode(EFFECT_CHANGE_RACE)
wr:SetValue(RACE_WARRIOR)
warrior:RegisterEffect(wr)
assert(xyz:GetLevel()==0,'Xyz acquired an ordinary Level')
assert(xyz:GetRitualLevel(ritual)==(OG_TEST_WITH_CIRCUIT and ((4<<16)|8) or 8),'Xyz Ritual Level lookup failed')
assert(xyz:GetRitualLevel(warrior)==0,'Non-Reptile Ritual incorrectly gained Rank')
local ne=naga:IsHasEffect(EFFECT_EXTRA_ATTACK)
assert(ne,'Naga field condition did not enable its aura')
assert(c990071008.atkcon(ne),'Naga condition without tp failed')
local re=Effect.CreateEffect(recovery)
re:SetType(EFFECT_TYPE_SINGLE)
re:SetCode(EFFECT_UPDATE_ATTACK)
recovery:RegisterEffect(re)
assert(c990071018.comeback(re)==false,'Recovery condition evaluation failed')
local ge=Effect.CreateEffect(grid)
ge:SetType(EFFECT_TYPE_SINGLE)
ge:SetCode(EFFECT_UPDATE_ATTACK)
grid:RegisterEffect(ge)
assert(c990071021.lockcon(ge)==false,'Grid condition evaluation failed')
local checked=false
local pooltest=Effect.CreateEffect(recovery)
pooltest:SetType(EFFECT_TYPE_FIELD|EFFECT_TYPE_CONTINUOUS)
pooltest:SetCode(EVENT_ADJUST)
pooltest:SetCondition(function(e,tp)
    assert(Duel.GetRitualMaterial(tp):IsContains(xyz),'Xyz absent from Ritual material pool')
    assert(Group.FromCards(xyz):CheckWithSumGreater(Card.GetRitualLevel,8,ritual),'Xyz Ritual sum failed')
    local rt=Ritual.Target(c990071004.ritparams)
    assert(rt(e,tp,nil,0,0,nil,0,0,0),'Ritual-from-Deck target check failed')
    checked=true
    return true
end)
Duel.RegisterEffect(pooltest,0)
pooltest:IsActivatable(0)
assert(checked,'pool test not executed')
Debug.Message('PASS real-engine Ritual pool, Rank lookup, unchanged Levels, and field callbacks')
